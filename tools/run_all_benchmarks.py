#!/usr/bin/env python3
import os
import shutil
import subprocess
import sys
import random

def main():
    bench_dir = "bench"
    results_dir = os.path.join(bench_dir, "results")
    artifacts_results_dir = os.path.join("BenchmarkDotNet.Artifacts", "results")

    # Clear previous artifacts to ensure fresh results
    if os.path.exists("BenchmarkDotNet.Artifacts"):
        shutil.rmtree("BenchmarkDotNet.Artifacts")
    for root, dirs, files in os.walk(bench_dir):
        if "BenchmarkDotNet.Artifacts" in dirs:
            shutil.rmtree(os.path.join(root, "BenchmarkDotNet.Artifacts"))

    # Find all benchmark projects
    all_projects = []
    for root, dirs, files in os.walk(bench_dir):
        # Ignore results dir and bin/obj dirs
        if "results" in root or "bin" in root or "obj" in root:
            continue
        for f in files:
            if f.endswith(".csproj") and "Autogenerated" not in f:
                all_projects.append(os.path.join(root, f))

    all_projects.sort()
    print(f"Found {len(all_projects)} total benchmark projects.")

    # Check existing results in bench/results
    existing_results = []
    if os.path.exists(results_dir):
        existing_results = os.listdir(results_dir)

    no_results_projects = []
    has_results_projects = []

    for p in all_projects:
        proj_name = os.path.splitext(os.path.basename(p))[0]
        # Check if any existing result starts with proj_name
        has_res = any(f.startswith(proj_name) for f in existing_results)
        if has_res:
            has_results_projects.append(p)
        else:
            no_results_projects.append(p)

    print(f"Projects without existing benchmarks: {len(no_results_projects)}")
    print(f"Projects with existing benchmarks:    {len(has_results_projects)}")

    # Select 10 projects
    target_count = 10
    selected_projects = []

    if len(no_results_projects) >= target_count:
        selected_projects = random.sample(no_results_projects, target_count)
        print(f"Selected {target_count} projects prioritizing those without benchmarks.")
    else:
        selected_projects = list(no_results_projects)
        remaining = target_count - len(selected_projects)
        if len(has_results_projects) > 0:
            to_select = min(remaining, len(has_results_projects))
            selected_projects.extend(random.sample(has_results_projects, to_select))
        print(f"Selected {len(selected_projects)} projects ({len(no_results_projects)} without benchmarks, {len(selected_projects) - len(no_results_projects)} with benchmarks).")

    failed = []
    passed = []

    for i, p in enumerate(selected_projects, 1):
        print(f"[{i}/{len(selected_projects)}] Running benchmark for: {p}")
        # Run under Dry job to ensure speed (<1-2 seconds per bench)
        cmd = ["dotnet", "run", "-c", "Release", "--project", p, "--", "--job", "Dry", "--filter", "*"]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"X {p} FAILED")
            print(res.stdout)
            print(res.stderr)
            failed.append(p)
        else:
            print(f"o {p} PASSED")
            passed.append(p)

    # Collect and copy all reports to bench/results
    os.makedirs(results_dir, exist_ok=True)
    copied_count = 0
    root_artifacts = os.path.join("BenchmarkDotNet.Artifacts", "results")
    if os.path.exists(root_artifacts):
        for f in os.listdir(root_artifacts):
            src_path = os.path.join(root_artifacts, f)
            if os.path.isfile(src_path):
                shutil.copy2(src_path, os.path.join(results_dir, f))
                copied_count += 1
    for root, dirs, files in os.walk(bench_dir):
        if "BenchmarkDotNet.Artifacts" in root and root.endswith("results"):
            for f in files:
                src_path = os.path.join(root, f)
                dest_path = os.path.join(results_dir, f)
                shutil.copy2(src_path, dest_path)
                copied_count += 1
    print(f"Copied {copied_count} benchmark reports to: {results_dir}")

    print("\n--- Benchmark Suite Run Summary ---")
    print(f"Selected projects: {len(selected_projects)}")
    print(f"Passed:            {len(passed)}")
    print(f"Failed:            {len(failed)}")

    if failed:
        print("\nFailed projects:")
        for fp in failed:
            print(f"  - {fp}")
        sys.exit(1)
    else:
        print("\nAll selected benchmarks ran successfully!")
        sys.exit(0)

if __name__ == "__main__":
    main()
