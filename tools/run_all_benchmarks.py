#!/usr/bin/env python3
import os
import shutil
import subprocess
import sys

def main():
    bench_dir = "bench"
    results_dir = os.path.join(bench_dir, "results")
    artifacts_results_dir = os.path.join("BenchmarkDotNet.Artifacts", "results")

    # Clear previous artifacts to ensure fresh results
    for root, dirs, files in os.walk(bench_dir):
        if "BenchmarkDotNet.Artifacts" in dirs:
            shutil.rmtree(os.path.join(root, "BenchmarkDotNet.Artifacts"))

    # Find all benchmark projects
    projects = []
    for root, dirs, files in os.walk(bench_dir):
        # Ignore results dir and bin/obj dirs
        if "results" in root or "bin" in root or "obj" in root:
            continue
        for f in files:
            if f.endswith(".csproj") and "Autogenerated" not in f:
                projects.append(os.path.join(root, f))

    projects.sort()
    print(f"Found {len(projects)} benchmark projects.")

    failed = []
    passed = []

    for i, p in enumerate(projects, 1):
        print(f"[{i}/{len(projects)}] Running benchmark for: {p}")
        # Run under Dry job to ensure speed (<1-2 seconds per bench)
        cmd = ["dotnet", "run", "-c", "Release", "--project", p, "--", "--job", "Dry"]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"X {p} FAILED")
            print(res.stdout)
            print(res.stderr)
            failed.append(p)
        else:
            print(f"o {p} PASSED")
            passed.append(p)

    # Collect and copy all reports to bench/results
    os.makedirs(results_dir, exist_ok=True)
    copied_count = 0
    for root, dirs, files in os.walk(bench_dir):
        if "BenchmarkDotNet.Artifacts" in root and root.endswith("results"):
            for f in files:
                src_path = os.path.join(root, f)
                dest_path = os.path.join(results_dir, f)
                shutil.copy2(src_path, dest_path)
                copied_count += 1
    print(f"Copied {copied_count} benchmark reports to: {results_dir}")

    print("\n--- Benchmark Suite Run Summary ---")
    print(f"Total projects: {len(projects)}")
    print(f"Passed:         {len(passed)}")
    print(f"Failed:         {len(failed)}")

    if failed:
        print("\nFailed projects:")
        for fp in failed:
            print(f"  - {fp}")
        sys.exit(1)
    else:
        print("\nAll benchmarks ran successfully!")
        sys.exit(0)

if __name__ == "__main__":
    main()
